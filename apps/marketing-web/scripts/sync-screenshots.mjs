#!/usr/bin/env node
/**
 * Copies the app's real native captures into the marketing site as WebP, per
 * device × locale × theme, and writes a typed manifest of what exists.
 *
 *   source: apps/app/store-assets/captures-native/<device>/<locale>/<theme>/<scene>.png
 *   output: apps/marketing-web/public/screenshots/<device>/<locale>/<theme>/<scene>.webp
 *           apps/marketing-web/src/lib/screenshot-manifest.generated.ts
 *
 * Only real app screens — never mock-ups. Re-run after `pnpm screenshots:*`:
 *   pnpm --filter marketing-web sync:screenshots
 */
import { existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const HERE = dirname(fileURLToPath(import.meta.url));
const APP = resolve(HERE, "..");
const SRC = resolve(APP, "../app/store-assets/captures-native");
const OUT = resolve(APP, "public/screenshots");
const MANIFEST = resolve(APP, "src/lib/screenshot-manifest.generated.ts");

const LOCALES = ["en", "ar", "ur"];

/**
 * Marketing device ← capture folder. `width` is the output width (≈2× the
 * largest rendered size); `themes` keeps the repo light (light mode only
 * where the site shows it).
 */
const DEVICES = [
  { id: "iphone", dir: "ios", width: 720, themes: ["dark", "light"] },
  { id: "android", dir: "android", width: 720, themes: ["dark"] },
  { id: "ipad", dir: "ipad", width: 1200, themes: ["dark"] },
  { id: "android-tablet", dir: "android-tablet", width: 1600, themes: ["dark"] },
  // Android TV has all three locales (tvOS is English-only); same app UI.
  { id: "tv", dir: "android-tv", width: 1600, themes: ["dark"] },
  // Apple TV (tvOS) — English-only captures; pages fall back to `tv` elsewhere.
  { id: "apple-tv", dir: "tvos", width: 1600, themes: ["dark"] },
];

/** Single-locale, unthemed captures: `<dir>/en/<file>.png` → `<id>/en/dark/<scene>.webp`. */
const FLAT = [
  {
    id: "watch",
    dir: "watch",
    width: 422,
    files: { schedule: "schedule", "next-salah": "morning" },
  },
  {
    id: "wear",
    dir: "wear-os",
    width: 454,
    files: { "salah-tile": "01-salah-tile", "tasbeeh-tile": "02-tasbeeh-tile" },
  },
];

const SCENE_ALIASES = { "names-of-allah": "names" };

async function convert(input, output, width) {
  mkdirSync(dirname(output), { recursive: true });
  const { width: w, height: h } = await sharp(input)
    .resize({ width, withoutEnlargement: true })
    .webp({ quality: 80, effort: 6 })
    .toFile(output);
  return { width: w, height: h };
}

// Only the device folders this script owns (other files, e.g. offline-data.webp, stay).
for (const { id } of [...DEVICES, ...FLAT]) rmSync(join(OUT, id), { recursive: true, force: true });
const manifest = {};
let count = 0;

for (const device of DEVICES) {
  const entry = { width: 0, height: 0, files: {} };
  for (const locale of LOCALES) {
    for (const theme of device.themes) {
      const dir = join(SRC, device.dir, locale, theme);
      if (!existsSync(dir)) continue;
      for (const file of readdirSync(dir)
        .filter((f) => f.endsWith(".png"))
        .sort()) {
        const raw = file.replace(/\.png$/, "");
        const scene = SCENE_ALIASES[raw] ?? raw;
        const size = await convert(
          join(dir, file),
          join(OUT, device.id, locale, theme, `${scene}.webp`),
          device.width,
        );
        entry.width = size.width;
        entry.height = size.height;
        entry.files[`${locale}/${theme}/${scene}`] = true;
        count++;
      }
    }
  }
  manifest[device.id] = entry;
}

for (const device of FLAT) {
  const entry = { width: 0, height: 0, files: {} };
  for (const [scene, file] of Object.entries(device.files)) {
    const input = join(SRC, device.dir, "en", `${file}.png`);
    if (!existsSync(input)) continue;
    const size = await convert(
      input,
      join(OUT, device.id, "en", "dark", `${scene}.webp`),
      device.width,
    );
    entry.width = size.width;
    entry.height = size.height;
    entry.files[`en/dark/${scene}`] = true;
    count++;
  }
  manifest[device.id] = entry;
}

const body = Object.entries(manifest)
  .map(([id, e]) => {
    const files = Object.keys(e.files)
      .sort()
      .map((f) => `      "${f}",`)
      .join("\n");
    return `  "${id}": {\n    width: ${e.width},\n    height: ${e.height},\n    files: [\n${files}\n    ],\n  },`;
  })
  .join("\n");

writeFileSync(
  MANIFEST,
  `// Generated by scripts/sync-screenshots.mjs — do not edit by hand.
// Real native captures per device: "<locale>/<theme>/<scene>" → /screenshots/<device>/<locale>/<theme>/<scene>.webp

export const SCREENSHOT_MANIFEST = {
${body}
} as const;
`,
);

console.log(
  `synced ${count} screenshots → public/screenshots, manifest → src/lib/screenshot-manifest.generated.ts`,
);

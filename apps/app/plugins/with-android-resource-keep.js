const fs = require("node:fs");
const path = require("node:path");
const { createRunOncePlugin, withDangerousMod } = require("@expo/config-plugins");

/**
 * Release builds run the resource shrinker (`enableShrinkResourcesInReleaseBuilds`).
 * It deletes resources that no code or XML references through `R.*`, and these
 * are only ever looked up by name at runtime:
 * - `@drawable/ic_tab_*` — NativeTabs `drawable="ic_tab_home"` (react-native-screens
 *   `getIdentifier`), copied by `with-android-tab-drawables`. Without them the
 *   bottom tab bar renders labels only.
 * - `@raw/adhan_*` — expo-notifications channel sounds (`android.resource://…/raw/adhan_*`).
 *   Without them every Adhan notification falls back to the default sound.
 * - `@layout/widget_preview_glance` — `AndroidWidgetPreviewPublisher` (Android 15
 *   generated widget-picker previews) inflates it via `getIdentifier`. The shrinker
 *   drops it even though the name is a string literal in Kotlin.
 * - `@mipmap/quick_*` — expo-quick-actions shortcut icons (`QUICK_ACTION_ANDROID_ICONS`),
 *   resolved by name when the long-press shortcuts are published.
 *
 * `tools:keep` in a raw XML file is AGP's documented escape hatch; the file itself
 * is not packaged. Distinct file name so it never replaces a library's `keep.xml`.
 * Audit after a release build: every app `res/` entry should be in
 * `aapt2 dump resources <apk>` (only this keep file is expected to be missing).
 */
const KEEP_FILE = "munib_tracker_keep.xml";
const KEEP_PATTERNS = [
  "@drawable/ic_tab_*",
  "@raw/adhan_*",
  "@layout/widget_preview_glance",
  "@mipmap/quick_*",
];

/** @param {string} rawDir */
function writeResourceKeep(rawDir) {
  fs.mkdirSync(rawDir, { recursive: true });
  const xml = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-android-resource-keep.js — do not edit. -->
<resources xmlns:tools="http://schemas.android.com/tools"
    tools:keep="${KEEP_PATTERNS.join(",")}" />
`;
  const file = path.join(rawDir, KEEP_FILE);
  fs.writeFileSync(file, xml);
  return file;
}

function withAndroidResourceKeep(config) {
  return withDangerousMod(config, [
    "android",
    async (config) => {
      writeResourceKeep(path.join(config.modRequest.platformProjectRoot, "app/src/main/res/raw"));
      return config;
    },
  ]);
}

module.exports = createRunOncePlugin(
  withAndroidResourceKeep,
  "with-android-resource-keep",
  "1.0.0",
);
module.exports.writeResourceKeep = writeResourceKeep;
module.exports.KEEP_PATTERNS = KEEP_PATTERNS;

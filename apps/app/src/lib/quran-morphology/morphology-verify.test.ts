/**
 * `pnpm --filter app morphology:verify` (scripts/morphology-verify.mjs) runs this
 * suite with MORPHOLOGY_FILE pointing at the downloaded, hash-checked corpus
 * file. In the normal test run it is skipped — the dataset is never committed.
 *
 * It runs the real pipeline over the whole Qur'an, aligns every corpus word with
 * the bundled text, writes docs/proofs/root-word-search-alignment.md and fails
 * on any unexplained mismatch.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { type AyahAlignmentReport, buildRootIndex } from "./build-index";
import { QAC_MORPHOLOGY, verifyMorphologyText } from "./source";

const FILE = process.env.MORPHOLOGY_FILE;
const run = FILE ? describe : describe.skip;

function loadSurahArabic(surah: number): Record<string, string> {
  const pad = String(surah).padStart(3, "0");
  return JSON.parse(
    readFileSync(join(__dirname, `../../../assets/data/quran/arabic/${pad}.json`), "utf8"),
  ) as Record<string, string>;
}

type Classified = AyahAlignmentReport & { kind: "split-join" | "unaligned" };

run("QAC morphology — full alignment against the bundled text", () => {
  it("parses, indexes and aligns every ayah", async () => {
    const text = verifyMorphologyText(readFileSync(FILE as string, "utf8"));
    const adjusted: Classified[] = [];
    const started = Date.now();
    const index = await buildRootIndex(text, {
      sourceHash: QAC_MORPHOLOGY.sha256,
      loadSurahArabic,
      onAyahAligned: (report) => {
        const identity =
          report.mapping.length === report.studyWords.length &&
          report.mapping.every((m, i) => m.length === 1 && m[0] === i);
        if (identity) return;
        const unaligned = report.mapping.some((m) => m.length === 0);
        adjusted.push({ ...report, kind: unaligned ? "unaligned" : "split-join" });
      },
    });
    const ms = Date.now() - started;
    const bytes = JSON.stringify(index).length;
    const unexplained = adjusted.filter((a) => a.kind === "unaligned");

    const rows = adjusted
      .map(
        (a) =>
          `| ${a.surah}:${a.ayah} | ${a.kind} | ${a.corpusWords.length} | ${a.studyWords.length} | ${a.mapping
            .map((m, i) => `${i + 1}→${m.length ? m.map((s) => s + 1).join("+") : "∅"}`)
            .join(" ")} |`,
      )
      .join("\n");

    const report = `# NF-3.22 root-word search — alignment report

Generated by \`pnpm --filter app morphology:verify\` (do not edit by hand).

- Source: Quranic Arabic Corpus morphology v${QAC_MORPHOLOGY.version}, sha256 \`${QAC_MORPHOLOGY.sha256}\` (LF-normalised), verified before use.
- Bundled text: \`apps/app/assets/data/quran/arabic/*.json\` split with \`splitAyahWords\`.
- Corpus words: ${index.stats.words.toLocaleString("en")} · root occurrences: ${index.stats.occurrences.toLocaleString("en")} · roots: ${index.stats.roots.toLocaleString("en")} · lemmas: ${index.stats.lemmas.toLocaleString("en")} · ayahs: ${index.stats.ayahs.toLocaleString("en")}
- Ayahs aligned one-to-one: ${(index.stats.ayahs - adjusted.length).toLocaleString("en")}
- Ayahs with an explained word join/split (fully mapped): ${adjusted.length - unexplained.length}
- Ayahs with an unexplained mismatch (some corpus word not placed): ${unexplained.length}
- Corpus words shown at ayah level (not attached to a word): ${index.stats.unalignedWords}
- Index size (JSON): ${(bytes / 1024).toFixed(0)} KB · build time on the dev machine: ${ms} ms

## Ayahs whose word split differs

Mapping column: corpus word → bundled word(s), 1-based; ∅ = shown at ayah level.

| Ayah | Kind | Corpus words | Bundled words | Mapping |
| --- | --- | --- | --- | --- |
${rows || "| — | — | — | — | — |"}
`;
    writeFileSync(
      join(__dirname, "../../../../../docs/proofs/root-word-search-alignment.md"),
      report,
    );

    expect(index.stats.occurrences).toBe(49_968);
    expect(index.stats.ayahs).toBe(6236);
    expect(unexplained.map((a) => `${a.surah}:${a.ayah}`)).toEqual([]);
  }, 300_000);
});

/**
 * Currencies whose official symbol is a single glyph that system fonts (and our
 * bundled Inter) do not yet render — Saudi Arabia (U+20C1, Unicode 17, 2025) and
 * the UAE (U+20C3, Unicode 18, due Sept 2026). We draw these as vector art via
 * {@link CurrencyGlyph} instead of relying on a Unicode codepoint that would tofu.
 * The `symbol` string stays a reliably-renderable fallback for any plain-text site.
 */

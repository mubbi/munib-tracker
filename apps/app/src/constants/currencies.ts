const currencyByCode = new Map(SUPPORTED_CURRENCIES.map((c) => [c.code, c]));

export function getCurrencyInfo(code: string): CurrencyDef | undefined {
  return currencyByCode.get(code);
}

/**
 * Symbol strings that should render as a vector glyph instead of plain text, paired
 * with their glyph kind. Used by MoneyText to detect a glyph currency inside an
 * already-formatted amount string (e.g. "ر.س1,234.56") without needing the code.
 * Symbols are unique across the catalogue, so substring matching is unambiguous.
 */
export const CURRENCY_GLYPH_SYMBOLS: ReadonlyArray<{
  symbol: string;
  glyph: CurrencyGlyphKind;
}> = SUPPORTED_CURRENCIES.flatMap((c) => (c.glyph ? [{ symbol: c.symbol, glyph: c.glyph }] : []));
